export type PixelIconName = keyof typeof pixelIcons;

export function iconRects(name: PixelIconName) {
  const rows = pixelIcons[name].split('\n').filter((r) => r.length > 0);
  const rects: { x: number; y: number; dim: boolean }[] = [];
  rows.forEach((row, y) => {
    [...row].forEach((c, x) => {
      if (c === '#' || c === '+') rects.push({ x, y, dim: c === '+' });
    });
  });
  const w = Math.max(...rows.map((r) => r.length));
  const h = rows.length;
  const size = Math.max(w, h) + 2;
  // centre the drawing in a square box with one pixel of air
  const ox = (size - w) / 2;
  const oy = (size - h) / 2;
  return { rects: rects.map((r) => ({ ...r, x: r.x + ox, y: r.y + oy })), size };
}
